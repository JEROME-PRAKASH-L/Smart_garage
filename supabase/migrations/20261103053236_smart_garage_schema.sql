create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  email text not null,
  mobile text,
  dob date,
  role text not null default 'customer' check (role in ('customer', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.services (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  price numeric(10, 2) not null default 0,
  duration text,
  created_at timestamptz not null default now()
);

create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  customer_id uuid not null references auth.users(id) on delete cascade,
  customer_name text not null,
  phone text,
  vehicle_number text not null,
  vehicle_type text,
  vehicle_brand text,
  vehicle_model text,
  service text not null,
  date date not null,
  time_slot text,
  pickup_type text not null default 'self' check (pickup_type in ('self', 'door')),
  delivery_type text not null default 'self-collect' check (delivery_type in ('self-collect', 'home-delivery')),
  address text,
  notes text,
  status text not null default 'pending' check (status in ('pending', 'inprogress', 'completed', 'rejected')),
  created_at timestamptz not null default now()
);

create table if not exists public.contacts (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text,
  message text not null,
  created_at timestamptz not null default now()
);

create index if not exists bookings_customer_id_idx on public.bookings(customer_id);
create index if not exists bookings_created_at_idx on public.bookings(created_at desc);
create index if not exists contacts_created_at_idx on public.contacts(created_at desc);

alter table public.profiles enable row level security;
alter table public.services enable row level security;
alter table public.bookings enable row level security;
alter table public.contacts enable row level security;

drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own" on public.profiles for select to authenticated using ((select auth.uid()) = id);

drop policy if exists "profiles_select_admin" on public.profiles;
create policy "profiles_select_admin" on public.profiles for select to authenticated using ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "services_public_read" on public.services;
create policy "services_public_read" on public.services for select to anon, authenticated using (true);

